from manim import *

# ---- function ----
f = lambda x: 5*np.cos(x/5)
R = 5                      # interval is 0 to R

# ---- camera ----
FLAT = dict(phi=90*DEGREES, theta=-90*DEGREES)
CAM  = dict(phi=70*DEGREES, theta=-60*DEGREES)

def make_axes():
    ax = ThreeDAxes(
        x_range=[-10, 10, 1], y_range=[-10, 10, 1], z_range=[-1, 6, 1],
        x_length=13, y_length=13, z_length=5.5,
        axis_config={"include_tip": False, "include_ticks": False})
    ax.shift(IN*2)
    ax.y_axis.set_opacity(0)
    return ax

def make_ticks(ax, x_max=10, z_max=6, size=0.08):
    g = VGroup()
    for x in range(-x_max, x_max + 1):
        if x != 0:
            g.add(Line(ax.c2p(x, 0, 0) + OUT*size, ax.c2p(x, 0, 0) + IN*size,
                       stroke_width=2))
    for z in range(1, z_max + 1):
        g.add(Line(ax.c2p(0, 0, z) + LEFT*size, ax.c2p(0, 0, z) + RIGHT*size,
                   stroke_width=2))
    return g

def tick_labels(ax, x_max=10, z_max=5, step=1):
    g = VGroup()
    for x in range(-x_max, x_max + 1, step):
        if x != 0:
            g.add(MathTex(f"{x}", font_size=20).move_to(ax.c2p(x, 0, 0) + IN*0.3))
    for z in range(step, z_max + 1, step):
        g.add(MathTex(f"{z}", font_size=20).move_to(ax.c2p(0, 0, z) + LEFT*0.3))
    g.add(MathTex("0", font_size=20).move_to(ax.c2p(0, 0, 0) + IN*0.3 + LEFT*0.3))
    return g

def make_tips(ax, x_max=10, z_max=6):
    tx = Triangle(color=WHITE, fill_opacity=1).scale(0.12).rotate(-PI/2)
    tx.move_to(ax.c2p(x_max, 0, 0))
    tz = Triangle(color=WHITE, fill_opacity=1).scale(0.12)
    tz.move_to(ax.c2p(0, 0, z_max))
    return VGroup(tx, tz)

def make_curve(ax, a=-5, b=5):
    return ParametricFunction(lambda t: ax.c2p(t, 0, f(t)),
                              t_range=[a, b], color=YELLOW)

def make_area(ax, b, a=0, n=60):
    xs = np.linspace(a, b, n)
    pts = [ax.c2p(x, 0, f(x)) for x in xs]
    pts += [ax.c2p(b, 0, 0), ax.c2p(a, 0, 0)]
    return Polygon(*pts, color=BLUE, fill_opacity=0.45, stroke_width=0)

def make_solid(ax, ang, b=5, op=0.5):
    top = Surface(lambda r, v: ax.c2p(r*np.cos(v), r*np.sin(v), f(r)),
                  u_range=[0, b], v_range=[0, ang], resolution=(12, 32),
                  fill_opacity=op, checkerboard_colors=[BLUE_D, BLUE_E],
                  stroke_width=0.3)
    wall = Surface(lambda u, v: ax.c2p(b*np.cos(v), b*np.sin(v), u),
                   u_range=[0, f(b)], v_range=[0, ang], resolution=(2, 32),
                   fill_color=BLUE_D, fill_opacity=op,
                   checkerboard_colors=False, stroke_width=0.3)
    base = Surface(lambda r, v: ax.c2p(r*np.cos(v), r*np.sin(v), 0),
                   u_range=[0, b], v_range=[0, ang], resolution=(2, 32),
                   fill_color=BLUE_E, fill_opacity=op,
                   checkerboard_colors=False, stroke_width=0.3)
    return VGroup(top, wall, base)

def make_strip(ax, xc, dx=0.5, op=0.85, a=0, b=5, color=None):
    x0, x1 = max(xc - dx/2, a), min(xc + dx/2, b)   # clip at the ends
    h = f(xc)
    color = color or (ORANGE if round(xc / dx) % 2 == 0 else TEAL)
    return Polygon(ax.c2p(x0, 0, 0), ax.c2p(x1, 0, 0),
                   ax.c2p(x1, 0, h), ax.c2p(x0, 0, h),
                   color=color, fill_opacity=op,
                   stroke_color=WHITE, stroke_width=2)

def make_shell(ax, xc, dx, ang, a=0, b=5, op=1, color=None):
    x0, x1 = max(xc - dx/2, a), min(xc + dx/2, b)
    h = f(xc)
    ang = max(ang, 0.001)
    color = color or (ORANGE if round(xc / dx) % 2 == 0 else TEAL)
    kw = dict(fill_color=color, fill_opacity=op,
              checkerboard_colors=False, stroke_width=0.3)
    parts = [
        Surface(lambda z, v: ax.c2p(x1*np.cos(v), x1*np.sin(v), z),
                u_range=[0, h], v_range=[0, ang], resolution=(6, 40), **kw),
        Surface(lambda r, v: ax.c2p(r*np.cos(v), r*np.sin(v), h),
                u_range=[x0, x1], v_range=[0, ang], resolution=(1, 40), **kw),
    ]
    if x0 > 1e-6:
        parts.append(
            Surface(lambda z, v: ax.c2p(x0*np.cos(v), x0*np.sin(v), z),
                    u_range=[0, h], v_range=[0, ang], resolution=(6, 40), **kw))
    return VGroup(*parts)

def make_strip_solid(ax, xc, dx=0.5, op=0.85, a=0, b=5):
    x0, x1 = max(xc - dx/2, a), min(xc + dx/2, b)
    h = f(xc)
    color = ORANGE if round(xc / dx) % 2 == 0 else TEAL
    return Surface(lambda u, v: ax.c2p(u, 0, v),
                   u_range=[x0, x1], v_range=[0, h], resolution=(2, 8),
                   fill_color=color, fill_opacity=op,
                   checkerboard_colors=False,
                   stroke_color=WHITE, stroke_width=2)

def make_chunk(ax, xc, dx, v0, v1, a=0, b=5, op=1):
    x0, x1 = max(xc - dx/2, a), min(xc + dx/2, b)
    h = f(xc)
    color = ORANGE if round(xc / dx) % 2 == 0 else TEAL
    kw = dict(fill_color=color, fill_opacity=op,
              checkerboard_colors=False, stroke_width=0)
    parts = [
        Surface(lambda z, v: ax.c2p(x1*np.cos(v), x1*np.sin(v), z),
                u_range=[0, h], v_range=[v0, v1], resolution=(3, 1), **kw),
        Surface(lambda r, v: ax.c2p(r*np.cos(v), r*np.sin(v), h),
                u_range=[x0, x1], v_range=[v0, v1], resolution=(1, 1), **kw),
    ]
    if x0 > 1e-6:
        parts.append(
            Surface(lambda z, v: ax.c2p(x0*np.cos(v), x0*np.sin(v), z),
                    u_range=[0, h], v_range=[v0, v1], resolution=(3, 1), **kw))
    return VGroup(*parts)

def make_shell_chunks(ax, xc, dx, K=30, a=0, b=5, op=1):
    return [make_chunk(ax, xc, dx, k*TAU/K, (k + 1)*TAU/K, a, b, op)
            for k in range(K)]



def make_shell_sweep(ax, xc, dx, ang, a=0, b=5, op=1):
    # shell swept to angle `ang`; face count grows with angle, so the edge is smooth
    x0, x1 = max(xc - dx/2, a), min(xc + dx/2, b)
    h = f(xc)
    ang = max(ang, 0.001)
    nv = max(2, int(np.ceil(48*ang/TAU)))
    color = ORANGE if round(xc / dx) % 2 == 0 else TEAL
    kw = dict(fill_color=color, fill_opacity=op,
              checkerboard_colors=False, stroke_width=0.3)
    parts = [
        Surface(lambda z, v: ax.c2p(x1*np.cos(v), x1*np.sin(v), z),
                u_range=[0, h], v_range=[0, ang], resolution=(3, nv), **kw),
        Surface(lambda r, v: ax.c2p(r*np.cos(v), r*np.sin(v), h),
                u_range=[x0, x1], v_range=[0, ang], resolution=(1, nv), **kw),
    ]
    if x0 > 1e-6:
        parts.append(
            Surface(lambda z, v: ax.c2p(x0*np.cos(v), x0*np.sin(v), z),
                    u_range=[0, h], v_range=[0, ang], resolution=(3, nv), **kw))
    return VGroup(*parts)
def make_unroll(ax, xc, dx, p, gamma_f=0.3, color=ORANGE, op=1):
    # p = 1: closed shell.  p = 0: flat slab in the plane x = xc.
    # Rolls like a carpet toward -y from the seam (+x side).
    x0, x1 = xc - dx/2, xc + dx/2
    h = f(xc)
    gam = gamma_f + (1 - gamma_f)*p                # stagger: 1 = true, gamma_f = reduced
    Sy = (1 - p) * np.pi * xc                      # pan so the final slab ends centred

    def P(r, t, z):                                # t: 0 = seam end, 1 = far end
        w = r - xc
        Lw = 2*np.pi*(xc + gam*w)                  # this layer's length
        yc = (1 - p) * Lw                          # flat part already laid out
        s = t * Lw
        if s <= yc:
            return ax.c2p(r, s - Sy, z)            # flat part
        psi = (s - yc) / r                         # remaining roll
        return ax.c2p(r*np.cos(psi), yc - Sy + r*np.sin(psi), z)

    kw = dict(fill_color=color, fill_opacity=op,
              checkerboard_colors=False, stroke_width=0.3)
    return VGroup(
        Surface(lambda t, z: P(x1, t, z), u_range=[0, 1], v_range=[0, h],
                resolution=(60, 2), **kw),                       # outer wall
        Surface(lambda t, z: P(x0, t, z), u_range=[0, 1], v_range=[0, h],
                resolution=(60, 2), **kw),                       # inner wall
        Surface(lambda r, t: P(r, t, h), u_range=[x0, x1], v_range=[0, 1],
                resolution=(1, 60), **kw),                       # top
        Surface(lambda r, t: P(r, t, 0), u_range=[x0, x1], v_range=[0, 1],
                resolution=(1, 60), **kw),                       # bottom
        Surface(lambda r, z: P(r, 0, z), u_range=[x0, x1], v_range=[0, h],
                resolution=(1, 1), **kw),                        # seam end face
        Surface(lambda r, z: P(r, 1, z), u_range=[x0, x1], v_range=[0, h],
                resolution=(1, 1), **kw),                        # far end face
    )

